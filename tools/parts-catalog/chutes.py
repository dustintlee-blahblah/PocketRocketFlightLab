#!/usr/bin/env python3
"""Shared writer for the app's own parachute lists (extra/*.orc), built from what each maker publishes.

Each maker's script lists its chutes as rows and calls write(); the rows hold only what the maker (or a retailer
quoting the maker) publishes, with the source given in the script. Nothing is taken from OpenRocket's component files.

A row: (part number, description, diameter in., Cd or None, line count or None, weight oz or None,
        packed diameter in. or None, packed length in. or None)

- Cd: the maker's own figure. Where a maker gives none, it is worked out from the maker's own rating, the weight the
  chute brings down at a stated speed, in sea-level air:  W = 1/2 rho v^2 Cd A  (cd_from_rating below).
- Line count: the maker's, else the gore count, else 8. Line length: not published by most makers; the chute's
  diameter is used (it only matters when no weight is listed).
- Weight: the listed weight. A chute with none gets the builder's weight from its fabric.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OZ, LB, IN, FT, G = 0.028349523125, 0.45359237, 0.0254, 0.3048, 9.80665
RHO = 1.225

FABRIC = "Nylon fabric, ripstop, 1.1 oz actual"
LINE = "Nylon cord, 1/16 in."


def cd_from_rating(dia_in, lb, fps):
    """The Cd (on the chute's diameter) that brings lb down at fps in sea-level air."""
    v = fps * FT
    return 2 * lb * LB * G / (RHO * v * v) / (math.pi / 4 * (dia_in * IN) ** 2)


def write(name, maker, rows, header):
    """Writes extra/<name>.orc. header: the comment at its top (what it is, where the numbers come from)."""
    out = []
    for pn, desc, dia, cd, lines, oz, pd, pl in rows:
        cd = round(cd, 2) if cd else 0.8
        lines = lines or 8
        extra = ""
        if oz:
            extra += f'\n            <Mass Unit="oz">{oz}</Mass>'
        if pd and pl:
            extra += f'\n            <PackedDiameter Unit="in">{pd}</PackedDiameter>\n            <PackedLength Unit="in">{pl}</PackedLength>'
        out.append(
            f"""        <Parachute>
            <Manufacturer>{maker}</Manufacturer>
            <PartNumber>{pn}</PartNumber>
            <Description>{desc}</Description>
            <Material Type="SURFACE">{FABRIC}</Material>
            <Diameter Unit="in">{dia}</Diameter>
            <DragCoefficient>{cd}</DragCoefficient>
            <LineCount>{lines}</LineCount>
            <LineLength Unit="in">{dia}</LineLength>
            <LineMaterial Type="LINE">{LINE}</LineMaterial>{extra}
        </Parachute>
"""
        )
    xml = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!--
{name}.orc - {header.strip()}
Generated by {name}.py beside tools/parts-catalog/ (see it for the sources); don't edit by hand.
-->
<OpenRocketComponent>
    <Version>0.1</Version>
    <Materials>
        <Material UnitsOfMeasure="kg/m"><Name>{LINE}</Name><Density>0.0016</Density><Type>LINE</Type></Material>
        <Material UnitsOfMeasure="kg/m2"><Name>{FABRIC}</Name><Density>0.0341</Density><Type>SURFACE</Type></Material>
    </Materials>
    <Components>
{"".join(out)}    </Components>
</OpenRocketComponent>
"""
    path = os.path.join(HERE, "extra", name + ".orc")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(xml)
    print("wrote", os.path.normpath(path), f"({len(rows)} parachutes)")
